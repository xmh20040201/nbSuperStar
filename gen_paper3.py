def sf(run, cn='宋体', en='Times New Roman', sz=12, b=False):
    run.font.size = Pt(sz); run.font.name = en; run.font.bold = b
    run.element.rPr.rFonts.set(qn('w:eastAsia'), cn)

def ah(text, lv=1, c=False):
    p = doc.add_paragraph()
    if c: p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if lv == 0:
        sf(p.add_run(text), '黑体', 'Times New Roman', 18, True)
        p.paragraph_format.space_after = Pt(16)
    elif lv == 1:
        sf(p.add_run(text), '黑体', 'Times New Roman', 14, True)
        p.paragraph_format.space_before = Pt(12)
        p.paragraph_format.space_after = Pt(6)
    elif lv == 2:
        sf(p.add_run(text), '黑体', 'Times New Roman', 12, True)
        p.paragraph_format.space_before = Pt(6)
        p.paragraph_format.space_after = Pt(4)
    return p

def ab(text, indent=True, sa=6):
    p = doc.add_paragraph()
    sf(p.add_run(text))
    pf = p.paragraph_format; pf.line_spacing = Pt(22); pf.space_after = Pt(sa)
    if indent: pf.first_line_indent = Cm(0.74)
    return p

def abb(pre, text):
    p = doc.add_paragraph()
    sf(p.add_run(pre), '宋体', 'Times New Roman', 12, True)
    sf(p.add_run(text))
    pf = p.paragraph_format; pf.line_spacing = Pt(22); pf.space_after = Pt(4)
    pf.first_line_indent = Cm(0.74)
    return p

def at(title, hdrs, rows):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sf(p.add_run(title), '宋体', 'Times New Roman', 11, True)
    p.paragraph_format.space_before = Pt(8); p.paragraph_format.space_after = Pt(4)
    t = doc.add_table(rows=1+len(rows), cols=len(hdrs))
    t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(hdrs):
        c = t.rows[0].cells[i]; c.text = ''
        cp = c.paragraphs[0]; cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        sf(cp.add_run(h), '宋体', 'Times New Roman', 11, True)
    for ri, row in enumerate(rows):
        for ci, v in enumerate(row):
            c = t.rows[ri+1].cells[ci]; c.text = ''
            cp = c.paragraphs[0]; cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
            sf(cp.add_run(str(v)), '宋体', 'Times New Roman', 11)
    return t


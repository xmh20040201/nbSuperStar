def set_font(run, name_cn='宋体', name_en='Times New Roman', size=12, bold=False):
    run.font.size = Pt(size)
    run.font.name = name_en
    run.font.bold = bold
    run.element.rPr.rFonts.set(qn('w:eastAsia'), name_cn)

def add_heading_text(text, level=1, center=False):
    p = doc.add_paragraph()
    if center:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if level == 0:
        set_font(p.add_run(text), '黑体', 'Times New Roman', 18, bold=True)
        p.paragraph_format.space_after = Pt(16)
    elif level == 1:
        set_font(p.add_run(text), '黑体', 'Times New Roman', 14, bold=True)
        p.paragraph_format.space_before = Pt(12)
        p.paragraph_format.space_after = Pt(6)
    elif level == 2:
        set_font(p.add_run(text), '黑体', 'Times New Roman', 12, bold=True)
        p.paragraph_format.space_before = Pt(6)
        p.paragraph_format.space_after = Pt(4)
    return p

def add_body(text, indent=True, space_after=6):
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_font(run, '宋体', 'Times New Roman', 12)
    pf = p.paragraph_format
    pf.line_spacing = Pt(22)
    pf.space_after = Pt(space_after)
    if indent:
        pf.first_line_indent = Cm(0.74)
    return p

def add_bold_body(prefix, text):
    p = doc.add_paragraph()
    set_font(p.add_run(prefix), '宋体', 'Times New Roman', 12, bold=True)
    set_font(p.add_run(text), '宋体', 'Times New Roman', 12)
    pf = p.paragraph_format
    pf.line_spacing = Pt(22)
    pf.space_after = Pt(4)
    pf.first_line_indent = Cm(0.74)
    return p

def add_table(title, headers, rows):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    set_font(p.add_run(title), '宋体', 'Times New Roman', 11, bold=True)
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after = Pt(4)
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = 'Table Grid'
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = ''
        cp = cell.paragraphs[0]
        cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        set_font(cp.add_run(h), '宋体', 'Times New Roman', 11, bold=True)
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            cell = table.rows[ri + 1].cells[ci]
            cell.text = ''
            cp = cell.paragraphs[0]
            cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
            set_font(cp.add_run(str(val)), '宋体', 'Times New Roman', 11)
    return table

